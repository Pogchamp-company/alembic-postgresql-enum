from enum import Enum
from typing import TYPE_CHECKING

from sqlalchemy import MetaData, Table, Column, insert
from sqlalchemy.dialects import postgresql

from tests.base.run_migration_test_abc import CompareAndRunTestCase

if TYPE_CHECKING:
    from sqlalchemy import Connection


class OldEnum(Enum):
    A = "a"
    B = "b"
    C = "c"


class NewEnum(Enum):
    A = "a"
    B = "b"
    C = "c"


class TestRenameEnum(CompareAndRunTestCase):
    """
    #115
    Unfortunately there is no way to add postgresql_using to alter_column in downgrade
    """

    disable_running = True

    def get_database_schema(self) -> MetaData:
        database_schema = MetaData()
        Table("a", database_schema, Column("value", postgresql.ENUM(OldEnum)))
        return database_schema

    def get_target_schema(self) -> MetaData:
        target_schema = MetaData()
        Table("a", target_schema, Column("value", postgresql.ENUM(NewEnum)))
        return target_schema

    def insert_migration_data(self, connection: "Connection", database_schema: MetaData) -> None:
        a_table = database_schema.tables["a"]
        connection.execute(
            insert(a_table).values(
                [
                    {"value": OldEnum.A.name},
                    {"value": OldEnum.B.name},
                    {"value": OldEnum.B.name},
                    {"value": OldEnum.C.name},
                ]
            )
        )

    def get_expected_upgrade(self) -> str:
        return """
            # ### commands auto generated by Alembic - please adjust! ###
            sa.Enum('A', 'B', 'C', name='newenum').create(op.get_bind())
            op.alter_column('a', 'value',
                       existing_type=postgresql.ENUM('A', 'B', 'C', name='oldenum'),
                       type_=postgresql.ENUM('A', 'B', 'C', name='newenum'),
                       existing_nullable=True,
                       postgresql_using='value::text::newenum')
            sa.Enum('A', 'B', 'C', name='oldenum').drop(op.get_bind())
            # ### end Alembic commands ###        
        """

    def get_expected_downgrade(self) -> str:
        return """
            # ### commands auto generated by Alembic - please adjust! ###
            sa.Enum('A', 'B', 'C', name='oldenum').create(op.get_bind())
            op.alter_column('a', 'value',
                       existing_type=postgresql.ENUM('A', 'B', 'C', name='newenum'),
                       type_=postgresql.ENUM('A', 'B', 'C', name='oldenum'),
                       existing_nullable=True)
            sa.Enum('A', 'B', 'C', name='newenum').drop(op.get_bind())
            # ### end Alembic commands ###
        """
